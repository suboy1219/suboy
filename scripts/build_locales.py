"""Generate the static English page and browser strings using only Python's stdlib.

Run from any directory: python scripts/build_locales.py
Chinese page: index.html. English translations: locales/en.json.
"""

from html import escape
from html.parser import HTMLParser
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parent.parent
TRANSLATIONS = json.loads((ROOT / "locales/en.json").read_text(encoding="utf-8"))
BASE = "https://suboy1219.github.io/suboy/"


def translate(value):
    key = value.strip()
    if key in TRANSLATIONS["text"]:
        return value[:len(value) - len(value.lstrip())] + TRANSLATIONS["text"][key] + value[len(value.rstrip()):]
    if re.search(r"[\u3400-\u9fff]", key) and key != "中文":
        raise ValueError(f"Missing English translation: {key}")
    return value


class EnglishPage(HTMLParser):
    def __init__(self):
        super().__init__(convert_charrefs=False)
        self.output = []

    def handle_decl(self, decl):
        self.output.append(f"<!{decl}>")

    def handle_comment(self, data):
        self.output.append(f"<!--{data}-->")

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if tag == "html":
            attrs["lang"] = "en"
        if tag == "link" and attrs.get("rel") == "canonical":
            attrs["href"] = BASE + "en/"
        if tag == "meta" and attrs.get("property") == "og:url":
            attrs["content"] = BASE + "en/"
        elif tag == "meta" and attrs.get("property") == "og:locale":
            attrs["content"] = "en_US"
        elif tag == "meta" and attrs.get("property") == "og:locale:alternate":
            attrs["content"] = "zh_CN"
        for key in ("alt", "aria-label", "placeholder", "content"):
            if attrs.get(key):
                attrs[key] = translate(attrs[key])
        for key in ("src", "href"):
            if attrs.get(key, "").startswith("./"):
                attrs[key] = "../" + attrs[key][2:]
        if attrs.get("data-language") == "zh":
            attrs.pop("aria-current", None)
        elif attrs.get("data-language") == "en":
            attrs["href"] = "./"
            attrs["aria-current"] = "page"
        encoded = "".join(f' {key}="{escape(value, quote=True)}"' if value is not None else f" {key}" for key, value in attrs.items())
        self.output.append(f"<{tag}{encoded}>")

    def handle_startendtag(self, tag, attrs):
        self.handle_starttag(tag, attrs)
        self.output[-1] = self.output[-1][:-1] + "/>"

    def handle_endtag(self, tag):
        self.output.append(f"</{tag}>")

    def handle_data(self, data):
        self.output.append(escape(translate(data), quote=False))

    def handle_entityref(self, name):
        self.output.append(f"&{name};")

    def handle_charref(self, name):
        self.output.append(f"&#{name};")


def main():
    page = EnglishPage()
    page.feed((ROOT / "index.html").read_text(encoding="utf-8"))
    page.close()
    english = ROOT / "en/index.html"
    english.parent.mkdir(exist_ok=True)
    english.write_text("".join(page.output), encoding="utf-8", newline="\n")
    runtime = {key: TRANSLATIONS[key] for key in ("ui", "search", "details")}
    (ROOT / "locales/en.js").write_text(
        "// Generated by scripts/build_locales.py; edit locales/en.json instead.\n"
        + "window.SuboyEnglish = " + json.dumps(runtime, ensure_ascii=False, indent=2) + ";\n",
        encoding="utf-8", newline="\n",
    )
    print("Generated en/index.html and locales/en.js")


if __name__ == "__main__":
    main()
